import assert from 'node:assert/strict'
import test from 'node:test'
import { Pool } from 'pg'
import { createPostgresKnowledgeRepository } from '../../repositories/postgres-knowledge-repository.js'

test('PostgreSQL knowledge preserves lifecycle, atomic versions, embeddings, and feedback attribution', async () => {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required for PostgreSQL integration tests')
  // The single connection retains temporary fixtures across repository transactions.
  const pool = new Pool({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 10_000, max: 1 })
  try {
    await pool.query(`
      CREATE TEMP TABLE knowledge_documents (LIKE public.knowledge_documents INCLUDING ALL);
      ALTER TABLE pg_temp.knowledge_documents ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE pg_temp.knowledge_documents ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
      CREATE TEMP TABLE knowledge_document_versions (LIKE public.knowledge_document_versions INCLUDING ALL);
      ALTER TABLE pg_temp.knowledge_document_versions ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE pg_temp.knowledge_document_versions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
      ALTER TABLE pg_temp.knowledge_document_versions ADD FOREIGN KEY (knowledge_document_id) REFERENCES pg_temp.knowledge_documents(id) ON DELETE CASCADE;
      ALTER TABLE pg_temp.knowledge_document_versions ADD CHECK (source_filename IS DISTINCT FROM 'reject-version');
      CREATE TEMP TABLE knowledge_embeddings (LIKE public.knowledge_embeddings INCLUDING ALL);
      ALTER TABLE pg_temp.knowledge_embeddings ADD FOREIGN KEY (knowledge_document_id) REFERENCES pg_temp.knowledge_documents(id) ON DELETE CASCADE;
      CREATE TEMP TABLE messages (id TEXT PRIMARY KEY, sources JSONB);
      CREATE TEMP TABLE feedback (message_id TEXT REFERENCES pg_temp.messages(id), rating INTEGER, feedback_type TEXT, quality_score DOUBLE PRECISION);
      SET search_path TO pg_temp;
    `)
    const repository = createPostgresKnowledgeRepository(pool)
    assert.deepEqual(await repository.getKnowledgeEmbeddingStats(), { count: 0, minimumDimensions: 0, maximumDimensions: 0, modelCount: 0 })
    const input = { title: 'Customer\'s refund policy', category: 'Policy', content: 'Original refund guidance', sourceFilename: 'refund.txt' }
    await assert.rejects(repository.createKnowledgeDocument({ ...input, sourceFilename: 'reject-version' }), { code: '23514' })
    assert.deepEqual(await repository.listKnowledge(), [])
    const document = await repository.createKnowledgeDocument(input)
    assert.equal(typeof document.id, 'number')
    assert.equal(document.status, 'indexed')
    assert.equal(document.archivedAt, null)
    const initial = (await repository.getKnowledgeDocumentVersions(document.id))[0]
    assert.equal(initial.knowledgeDocumentId, document.id)
    assert.equal(initial.version, 1)
    assert.equal(initial.sourceFilename, input.sourceFilename)
    assert.equal(initial.createdAt, document.updatedAt)
    const fallback = await repository.createKnowledgeDocument({ title: 'General policy', category: 'Policy', content: 'Fallback guidance', status: 'review' })
    assert.deepEqual((await repository.listKnowledgeEmbeddingCandidates()).map(({ id, contentHash }) => ({ id, contentHash })), [{ id: document.id, contentHash: null }])
    const embedding = { knowledgeDocumentId: document.id, model: 'test-model', vector: [0.5, -0.25], contentHash: 'original-hash' }
    await repository.upsertKnowledgeEmbedding(embedding)
    const replacement = { ...embedding, model: 'test-model-2', vector: [0.5, -0.25, 0], contentHash: 'new-hash' }
    await repository.upsertKnowledgeEmbedding(replacement)
    assert.deepEqual((await repository.listEmbeddedKnowledge())[0].vector, replacement.vector)
    assert.equal((await repository.listKnowledgeEmbeddingCandidates())[0].contentHash, replacement.contentHash)
    assert.deepEqual(await repository.getKnowledgeEmbeddingStats(), { count: 1, minimumDimensions: 3, maximumDimensions: 3, modelCount: 1 })
    await assert.rejects(repository.updateKnowledgeDocument(document.id, { ...input, content: 'Rejected update', sourceFilename: 'reject-version' }), { code: '23514' })
    assert.equal((await repository.listEmbeddedKnowledge())[0].content, input.content)
    assert.equal((await repository.getKnowledgeDocumentVersions(document.id)).length, 1)

    for (const [id, sources, rating, type, quality] of [
      ['m1', ['Missing source', document.title, fallback.title], 4, 'customer_rating', 80],
      ['m2', [null, document.title], null, 'edited', 60],
      ['m3', { title: document.title }, 1, 'rejected', 0],
    ] as const) {
      await pool.query('INSERT INTO messages (id, sources) VALUES ($1, $2::jsonb)', [id, JSON.stringify(sources)])
      await pool.query('INSERT INTO feedback VALUES ($1, $2, $3, $4)', [id, rating, type, quality])
    }
    assert.deepEqual(await repository.getKnowledgeSourceFeedbackStats(), [{ title: document.title, feedbackCount: 2, averageQuality: 70, averageRating: 4, acceptedCount: 0, editedCount: 1, rejectedCount: 0 }])
    await repository.incrementKnowledgeUses(document.title)
    assert.equal((await repository.listKnowledge())[0].uses, 1)
    assert.deepEqual(await repository.archiveKnowledgeDocuments([document.id, document.id, -1]), { archived: 1 })
    assert.ok((await repository.listArchivedKnowledge())[0].archivedAt)
    assert.deepEqual(await repository.listEmbeddedKnowledge(), [])
    assert.deepEqual(await repository.listKnowledgeEmbeddingCandidates(), [])
    assert.equal(await repository.updateKnowledgeDocument(document.id, input), null)
    assert.deepEqual(await repository.getKnowledgeSourceFeedbackStats(), [{ title: fallback.title, feedbackCount: 1, averageQuality: 80, averageRating: 4, acceptedCount: 0, editedCount: 0, rejectedCount: 0 }])
    assert.deepEqual(await repository.restoreKnowledgeDocuments([document.id]), { restored: 1 })
    assert.equal((await repository.listEmbeddedKnowledge())[0].id, document.id)
    const updated = await repository.updateKnowledgeDocument(document.id, { ...input, content: 'Revised guidance' })
    assert.equal(updated?.content, 'Revised guidance')
    assert.deepEqual((await repository.getKnowledgeDocumentVersions(document.id)).map((item) => item.version), [2, 1])
    assert.deepEqual(await repository.listEmbeddedKnowledge(), [])
    await repository.upsertKnowledgeEmbedding(embedding)
    assert.deepEqual(await repository.deleteKnowledgeDocuments([document.id]), { deleted: 1 })
    assert.deepEqual(await repository.getKnowledgeDocumentVersions(document.id), [])
    assert.equal((await repository.getKnowledgeEmbeddingStats()).count, 0)
  } finally { await pool.end() }
})
