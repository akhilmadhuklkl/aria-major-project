import assert from 'node:assert/strict'
import test from 'node:test'
import { Pool } from 'pg'
import { createPostgresConversationRepository } from '../../repositories/postgres-conversation-repository.js'

test('PostgreSQL conversations support queues, independent messages, partial updates, and customer history', async () => {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required for PostgreSQL integration tests')
  const pool = new Pool({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 10_000 })
  try {
    const client = await pool.connect()
    try {
      await client.query('BEGIN')
      await client.query(`
        CREATE TEMP TABLE conversations (LIKE public.conversations INCLUDING ALL) ON COMMIT DROP;
        ALTER TABLE pg_temp.conversations ALTER COLUMN id DROP DEFAULT;
        ALTER TABLE pg_temp.conversations ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        CREATE TEMP TABLE messages (LIKE public.messages INCLUDING ALL) ON COMMIT DROP;
        ALTER TABLE pg_temp.messages ADD FOREIGN KEY (conversation_id) REFERENCES pg_temp.conversations(id);
      `)
      const repository = createPostgresConversationRepository(client)
      const now = '2026-01-01T00:00:00.000Z'
      const base = { customerName: 'Test Customer', subject: 'Refund request', status: 'open' as const, priority: 'high' as const, topic: 'Refunds', tags: ['refund'], assignedTo: 'Agent', escalated: true, createdAt: now, updatedAt: now }
      const first = await repository.createConversation(base)
      const second = await repository.createConversation({ ...base, subject: 'Previous support', tags: ['refund'], assignedTo: null, escalated: false, updatedAt: '2026-01-02T00:00:00.000Z' })
      const third = await repository.createConversation({ ...base, customerName: 'Refund Visitor', subject: 'Other question', tags: [], assignedTo: null, status: 'resolved', escalated: false, updatedAt: '2026-01-03T00:00:00.000Z' })
      assert.equal(typeof first.id, 'number')
      assert.deepEqual(await repository.getConversation(first.id), { ...base, id: first.id })
      assert.equal((await repository.listConversations()).length, 3)
      const page = await repository.listConversationPage(2, 0, 'REFUND')
      assert.equal(page.total, 3)
      assert.deepEqual(page.items.map((item) => item.id), [third.id, second.id])
      assert.deepEqual(page.queueCounts, { mine: 1, unassigned: 2, attention: 2 })
      assert.deepEqual((await repository.listConversationPage(2, 2, 'REFUND')).items.map((item) => item.id), [first.id])
      const filtered = await repository.listConversationPage(2, 0, 'Visitor')
      assert.equal(filtered.total, 1)
      assert.deepEqual(filtered.queueCounts, page.queueCounts)
      assert.equal((await repository.listConversationPage(2, 0, '')).total, 3)
      assert.equal((await repository.listConversationPage(2, 0, 'no-match')).total, 0)
      const updated = await repository.updateConversation(first.id, { status: 'pending', assignedTo: undefined, tags: undefined, escalated: undefined })
      assert.equal(updated?.assignedTo, 'Agent')
      assert.deepEqual(updated?.tags, ['refund'])
      assert.equal(updated?.escalated, true)
      assert.equal(updated?.priority, 'high')
      const cleared = await repository.updateConversation(first.id, { assignedTo: null, tags: [], escalated: false })
      assert.equal(cleared?.status, 'pending')
      assert.equal(cleared?.assignedTo, null)
      assert.deepEqual(cleared?.tags, [])
      assert.equal(cleared?.escalated, false)
      assert.equal(await repository.updateConversation(-1, { status: 'pending' }), undefined)
      const answer = { id: crypto.randomUUID(), conversationId: first.id, role: 'assistant', content: 'Verified answer', confidence: 0.85, sources: ['Policy'], sourceScores: [{ title: 'Policy', score: 0.85 }], retrievalMethod: 'hybrid', generationProvider: 'local-knowledge', latencyMs: 12, shouldEscalate: false, createdAt: now }
      await repository.appendMessage(answer)
      await repository.appendMessage({ ...answer, id: crypto.randomUUID(), role: 'customer', content: 'Follow-up', createdAt: '2026-01-03T00:00:00.000Z' })
      await repository.appendMessage({ ...answer, id: crypto.randomUUID(), conversationId: second.id, role: 'customer', content: 'Previous interaction' })
      const messages = await repository.listMessages(first.id)
      assert.equal(messages.length, 2)
      assert.deepEqual(messages[0], answer)
      assert.equal(await repository.getLatestAssistantMessageId(first.id), answer.id)
      assert.equal(await repository.getLatestAssistantMessageId(second.id), undefined)
      assert.deepEqual(await repository.listMessages(third.id), [])
      const context = await repository.getCustomerContext(first.id)
      assert.ok(context)
      assert.equal(context.customer, 'Test Customer')
      assert.equal(context.totalConversations, 2)
      assert.equal(context.openConversations, 2)
      assert.deepEqual(context.topics, [{ topic: 'Refunds', count: 2 }])
      assert.equal(context.history.length, 1)
      assert.equal(context.history[0].id, second.id)
      assert.equal(context.history[0].lastMessage, 'Previous interaction')
      assert.equal(await repository.getCustomerContext(-1), undefined)
    } finally {
      await client.query('ROLLBACK')
      client.release()
    }
  } finally { await pool.end() }
})
