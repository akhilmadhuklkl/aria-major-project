import assert from 'node:assert/strict'
import test from 'node:test'
import { Pool } from 'pg'
import { createPostgresGraphRepository } from '../../repositories/postgres-graph-repository.js'

test('PostgreSQL graph repository preserves properties, paths, lookup, and cascade deletion', async () => {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required for PostgreSQL integration tests')
  const pool = new Pool({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 10_000, max: 1 })
  const client = await pool.connect()
  try {
    await client.query('BEGIN')
    await client.query(`
      CREATE TEMP TABLE graph_nodes (LIKE public.graph_nodes INCLUDING ALL) ON COMMIT DROP;
      CREATE TEMP TABLE graph_relationships (LIKE public.graph_relationships INCLUDING ALL) ON COMMIT DROP;
      ALTER TABLE pg_temp.graph_relationships ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE pg_temp.graph_relationships ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
      ALTER TABLE pg_temp.graph_relationships ADD FOREIGN KEY (source_id) REFERENCES pg_temp.graph_nodes(id) ON DELETE CASCADE;
      ALTER TABLE pg_temp.graph_relationships ADD FOREIGN KEY (target_id) REFERENCES pg_temp.graph_nodes(id) ON DELETE CASCADE;
      SET search_path TO pg_temp;
    `)
    const repository = createPostgresGraphRepository(client)
    const first = await repository.upsertGraphNode({ id: 'issue', type: 'SupportIssue', properties: { title: 'Refund delay', active: false, count: 0, optional: null } })
    await repository.upsertGraphNode({ id: 'procedure', type: 'SupportProcedure' })
    await repository.upsertGraphNode({ id: 'knowledge', type: 'KnowledgeDocument', properties: { title: 'Verified policy' } })
    assert.deepEqual(first?.properties, { title: 'Refund delay', active: false, count: 0, optional: null })
    const createdAt = (await repository.getGraphNode('issue'))?.createdAt
    const updated = await repository.upsertGraphNode({ id: 'issue', type: 'SupportAgent', properties: { title: 'Refund delay', status: 'updated' } })
    assert.equal(updated?.createdAt, createdAt)
    assert.equal(updated?.type, 'SupportAgent')
    await repository.createGraphRelationship({ sourceId: 'issue', type: 'RESOLVED_BY', targetId: 'procedure' })
    await repository.createGraphRelationship({ sourceId: 'issue', type: 'RESOLVED_BY', targetId: 'procedure', properties: { verified: true } })
    await repository.createGraphRelationship({ sourceId: 'procedure', type: 'SUPPORTED_BY', targetId: 'knowledge' })
    await repository.createGraphRelationship({ sourceId: 'knowledge', type: 'ABOUT', targetId: 'issue' })
    assert.equal((await repository.listGraphRelationships()).length, 3)
    assert.deepEqual((await repository.listGraphRelationships()).find((item) => item.sourceId === 'issue')?.properties, { verified: true })
    await client.query('SAVEPOINT missing_graph_relation')
    await assert.rejects(repository.createGraphRelationship({ sourceId: 'missing', type: 'OWNS', targetId: 'procedure' }), { code: '23503' })
    await client.query('ROLLBACK TO SAVEPOINT missing_graph_relation')
    const paths = await repository.queryGraphPaths('issue', 99)
    assert.ok(paths.some((path) => path.nodes.join(',') === 'issue,procedure,knowledge'))
    assert.ok(paths.every((path) => path.relationships.length <= 2 && new Set(path.nodes).size === path.nodes.length))
    assert.deepEqual(await repository.queryGraphPaths('missing'), [])
    assert.deepEqual(await repository.findGraphKnowledgeTitles('refund'), ['Verified policy'])
    assert.deepEqual(await repository.findGraphKnowledgeTitles('unrelated'), [])
    assert.deepEqual(await repository.findGraphKnowledgeTitles(''), [])
    assert.equal(await repository.deleteGraphNode('knowledge'), true)
    assert.deepEqual(await repository.listGraphRelationships(), [{ sourceId: 'issue', type: 'RESOLVED_BY', targetId: 'procedure', properties: { verified: true }, createdAt: (await repository.listGraphRelationships())[0].createdAt }])
    assert.equal(await repository.deleteGraphNode('knowledge'), false)
  } finally {
    await client.query('ROLLBACK')
    client.release()
    await pool.end()
  }
})
