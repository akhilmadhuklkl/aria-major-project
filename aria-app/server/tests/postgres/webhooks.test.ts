import assert from 'node:assert/strict'
import test from 'node:test'
import { Pool } from 'pg'
import { createPostgresWebhookRepository } from '../../repositories/postgres-webhook-repository.js'
import { runWebhookRepositoryContract } from '../contracts/repository-contracts.js'

test('PostgreSQL webhook repository preserves subscriptions, deliveries, and cascade deletion', async () => {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required for PostgreSQL integration tests')
  const pool = new Pool({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 10_000, max: 1 })
  try {
    await pool.query(`
      CREATE TEMP TABLE webhook_subscriptions (LIKE public.webhook_subscriptions INCLUDING ALL);
      ALTER TABLE pg_temp.webhook_subscriptions ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE pg_temp.webhook_subscriptions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
      CREATE TEMP TABLE webhook_delivery_logs (LIKE public.webhook_delivery_logs INCLUDING ALL);
      ALTER TABLE pg_temp.webhook_delivery_logs ALTER COLUMN id DROP DEFAULT;
      ALTER TABLE pg_temp.webhook_delivery_logs ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
      ALTER TABLE pg_temp.webhook_delivery_logs ADD FOREIGN KEY (webhook_id) REFERENCES pg_temp.webhook_subscriptions(id) ON DELETE CASCADE;
      SET search_path TO pg_temp;
    `)
    const repository = createPostgresWebhookRepository(pool)
    await pool.query('BEGIN')
    await pool.query('SAVEPOINT webhook_repository_contract')
    try {
      await runWebhookRepositoryContract(repository, `postgres-webhook-${Date.now()}`)
    } finally {
      await pool.query('ROLLBACK TO SAVEPOINT webhook_repository_contract')
      await pool.query('RELEASE SAVEPOINT webhook_repository_contract')
    }
    const now = '2026-01-01T00:00:00.000Z'
    const input = { name: 'Integration webhook', url: `https://example.com/${crypto.randomUUID()}`, secret: 'integration-secret', events: ['knowledge.indexed'], createdAt: now, updatedAt: now }
    const id = await repository.insertSubscription(input)
    assert.equal(typeof id, 'number')
    assert.deepEqual((await repository.listSubscriptionsWithSecrets())[0], { id, ...input, active: true })
    assert.equal(await repository.updateSubscription(id, false, '2026-01-02T00:00:00.000Z'), true)
    assert.equal((await repository.listSubscriptionsWithSecrets())[0].active, false)
    await repository.insertDelivery({ webhookId: id, event: 'knowledge.indexed', status: 'failed', responseStatus: 503, attempts: 3, error: 'HTTP 503', createdAt: now })
    const delivery = (await repository.listDeliveries())[0]
    assert.deepEqual({ ...delivery, createdAt: now }, { id: delivery.id, webhookId: id, name: input.name, event: 'knowledge.indexed', status: 'failed', responseStatus: 503, attempts: 3, error: 'HTTP 503', createdAt: now })
    assert.equal('secret' in delivery, false)
    assert.equal(await repository.deleteSubscription(id), true)
    assert.equal(await repository.deleteSubscription(id), false)
    const remaining = await pool.query('SELECT COUNT(*)::int AS count FROM webhook_delivery_logs WHERE webhook_id = $1', [id])
    assert.equal(remaining.rows[0].count, 0)
    await pool.query('ROLLBACK')
  } finally {
    await pool.end()
  }
})
