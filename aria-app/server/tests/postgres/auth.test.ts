import assert from 'node:assert/strict'
import test from 'node:test'
import { Pool } from 'pg'
import { createPostgresAuthRepository } from '../../repositories/postgres-auth-repository.js'
import { runAuthRepositoryContract } from '../contracts/repository-contracts.js'

test('PostgreSQL authentication repository preserves user, credential, and session lifecycle', async () => {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required for PostgreSQL integration tests')
  const pool = new Pool({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 10_000 })
  try {
    const client = await pool.connect()
    try {
      await client.query('BEGIN')
      await client.query(`
        CREATE TEMP TABLE users (LIKE public.users INCLUDING ALL) ON COMMIT DROP;
        ALTER TABLE pg_temp.users ALTER COLUMN id DROP DEFAULT;
        ALTER TABLE pg_temp.users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        CREATE TEMP TABLE sessions (LIKE public.sessions INCLUDING ALL) ON COMMIT DROP;
        ALTER TABLE pg_temp.sessions ALTER COLUMN id DROP DEFAULT;
        ALTER TABLE pg_temp.sessions ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        ALTER TABLE pg_temp.sessions ADD FOREIGN KEY (user_id) REFERENCES pg_temp.users(id) ON DELETE CASCADE;
      `)
      const repository = createPostgresAuthRepository(client)
      await repository.ensureSchema()
      await client.query('SAVEPOINT auth_repository_contract')
      try {
        await runAuthRepositoryContract(repository, `postgres-auth-${Date.now()}`)
      } finally {
        await client.query('ROLLBACK TO SAVEPOINT auth_repository_contract')
        await client.query('RELEASE SAVEPOINT auth_repository_contract')
      }
      assert.equal(await repository.countUsers(), 0)
      const now = '2026-01-01T00:00:00.000Z'
      const input = { id: 0, email: 'Agent@Example.com', displayName: 'Agent', role: 'support_agent' as const, passwordHash: 'test-hash', passwordSalt: 'test-salt', createdAt: now, updatedAt: now }
      const id = await repository.insertUser(input)
      const user = { id, email: input.email, displayName: input.displayName, role: input.role }
      assert.deepEqual(await repository.findUserById(id), user)
      assert.deepEqual(await repository.findUserByEmail('AGENT@EXAMPLE.COM'), { ...user, passwordHash: input.passwordHash, passwordSalt: input.passwordSalt })
      assert.equal(await repository.findUserByEmail('missing@example.com'), undefined)
      assert.deepEqual(await repository.findCredentialsByUserId(id), { passwordHash: input.passwordHash, passwordSalt: input.passwordSalt })
      await repository.insertUser({ ...input, email: 'customer@example.com', displayName: 'Customer', role: 'customer' })
      assert.equal(await repository.countUsers(), 2)
      assert.deepEqual(await repository.listSupportAgents(), [user])
      const users = await repository.listUsers()
      assert.equal(users.length, 2)
      assert.ok(users.every((item) => !('passwordHash' in item) && !('passwordSalt' in item)))
      await client.query('SAVEPOINT duplicate_email')
      await assert.rejects(repository.insertUser({ ...input, email: 'agent@example.com' }), (error: unknown) => (error as { code?: string }).code === '23505')
      await client.query('ROLLBACK TO SAVEPOINT duplicate_email')
      await client.query('RELEASE SAVEPOINT duplicate_email')
      const expiresAt = '2026-01-01T08:00:00.000Z'
      await repository.insertSession({ userId: id, tokenHash: 'first-hash', expiresAt, createdAt: now })
      await repository.insertSession({ userId: id, tokenHash: 'second-hash', expiresAt, createdAt: now })
      assert.deepEqual(await repository.findUserByToken('first-hash'), { ...user, expiresAt })
      assert.equal(await repository.findUserByToken('missing'), undefined)
      await repository.revokeSession('first-hash', now)
      assert.equal(await repository.findUserByToken('first-hash'), undefined)
      assert.ok(await repository.findUserByToken('second-hash'))
      await repository.updateCredentials(id, { passwordHash: 'new-hash', passwordSalt: 'new-salt' }, expiresAt)
      assert.deepEqual(await repository.findCredentialsByUserId(id), { passwordHash: 'new-hash', passwordSalt: 'new-salt' })
      await repository.revokeUserSessions(id, expiresAt)
      assert.equal(await repository.findUserByToken('second-hash'), undefined)
      await client.query('DELETE FROM pg_temp.users WHERE id = $1', [id])
      assert.equal(await repository.findUserById(id), undefined)
      const remaining = await client.query('SELECT COUNT(*)::int AS count FROM pg_temp.sessions WHERE user_id = $1', [id])
      assert.equal(remaining.rows[0].count, 0)
    } finally {
      await client.query('ROLLBACK')
      client.release()
    }
  } finally { await pool.end() }
})
