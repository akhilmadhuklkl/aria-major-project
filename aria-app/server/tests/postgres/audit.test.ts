import assert from 'node:assert/strict'
import test from 'node:test'
import { Pool } from 'pg'
import { createPostgresAuditRepository } from '../../repositories/postgres-audit-repository.js'
import { runAuditRepositoryContract } from '../contracts/repository-contracts.js'

test('PostgreSQL audit round-trips metadata, defaults, and actor deletion', async () => {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required for PostgreSQL integration tests')
  const pool = new Pool({ connectionString: process.env.DATABASE_URL, connectionTimeoutMillis: 10_000 })
  try {
    const client = await pool.connect()
    try {
      await client.query('BEGIN')
      await client.query(`
        CREATE TEMP TABLE users (id BIGINT PRIMARY KEY) ON COMMIT DROP;
        CREATE TEMP TABLE audit_logs (LIKE public.audit_logs INCLUDING ALL) ON COMMIT DROP;
        ALTER TABLE pg_temp.audit_logs ALTER COLUMN id DROP DEFAULT;
        ALTER TABLE pg_temp.audit_logs ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        ALTER TABLE pg_temp.audit_logs ADD FOREIGN KEY (actor_user_id) REFERENCES pg_temp.users(id) ON DELETE SET NULL;
        INSERT INTO pg_temp.users VALUES (7);
      `)
      const repository = createPostgresAuditRepository(client)
      await client.query('SAVEPOINT audit_repository_contract')
      try {
        await runAuditRepositoryContract(repository, `postgres-audit-${Date.now()}`)
      } finally {
        await client.query('ROLLBACK TO SAVEPOINT audit_repository_contract')
        await client.query('RELEASE SAVEPOINT audit_repository_contract')
      }
      assert.deepEqual(await repository.listAuditLogs(), [])
      const metadata = { nested: { events: ['knowledge.indexed'] }, active: false, count: 0 }
      const entry = await repository.createAuditLog({ actorUserId: 7, actorEmail: 'agent@example.com', action: 'webhook.paused', entityType: 'webhook', entityId: 0, metadata })
      const stored = (await repository.listAuditLogs()).find((item) => item.id === entry.id)
      assert.deepEqual(stored, { id: entry.id, actorUserId: 7, actorEmail: 'agent@example.com', action: 'webhook.paused', entityType: 'webhook', entityId: '0', metadata, createdAt: entry.createdAt })
      const minimal = await repository.createAuditLog({ action: 'test', entityType: 'test' })
      const defaults = (await repository.listAuditLogs()).find((item) => item.id === minimal.id)
      assert.ok(defaults)
      assert.equal(defaults.actorUserId, null)
      assert.equal(defaults.actorEmail, 'local-demo')
      assert.equal(defaults.entityId, null)
      assert.deepEqual(defaults.metadata, {})
      assert.equal((await repository.listAuditLogs(1)).length, 1)
      await client.query('DELETE FROM pg_temp.users WHERE id = 7')
      const orphan = (await repository.listAuditLogs()).find((item) => item.id === entry.id)
      assert.equal(orphan?.actorUserId, null)
      assert.equal(orphan?.actorEmail, 'agent@example.com')
      assert.deepEqual(orphan?.metadata, metadata)
    } finally {
      await client.query('ROLLBACK')
      client.release()
    }
  } finally { await pool.end() }
})
